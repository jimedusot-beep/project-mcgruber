import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
async function donor(page,kind="mouse") {
  await page.goto("/#/salvage");
  await page.getByRole("button",{name:"+ Add donor device"}).click();
  await page.getByLabel("Device name",{exact:true}).fill("QA donor — software fixture");
  await page.getByLabel("Device type",{exact:true}).selectOption(kind);
  await page.getByRole("button",{name:"Save donor device",exact:true}).click();
  await expect(page.locator("#save-status")).toHaveText("Saved on this device");
}
