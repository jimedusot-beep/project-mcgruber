test("invalid draft import preserves existing notebook records and current workspace",async({page},info)=>{
  await donor(page);
  await page.goto("/#/notebook");
  await page.getByRole("button",{name:"+ New experiment",exact:true}).click();
  await page.getByLabel("Experiment name",{exact:true}).fill("QA preserved observation");
  await page.getByRole("button",{name:"Save experiment",exact:true}).click();
  await expect(page.locator("#save-status")).toHaveText("Saved on this device");
  await page.goto("/#/settings");
  const pending=page.waitForEvent("download");await page.getByRole("button",{name:"Download full backup",exact:true}).click();
  const download=await pending, filename=info.outputPath("before.json");await download.saveAs(filename);
  const data=JSON.parse(await readFile(filename,"utf8"));
  data.workspace.draftRecord={id:"bad",name:"",project:"P04",evidence:"Reported observation",result:"Not tested",date:"bad-date",attachments:[]};
  page.once("dialog",d=>d.accept());await page.locator("#restore-backup").setInputFiles({name:"invalid.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(data))});
  await expect(page.locator("#backup-status")).toContainText("Invalid experiment date");
  await page.goto("/#/salvage");await expect(page.locator("#donor-list")).toContainText("QA donor");
  await page.goto("/#/notebook");await expect(page.locator(".record")).toContainText("QA preserved observation");
});
