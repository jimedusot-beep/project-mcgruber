  await page.getByRole("button",{name:"4. Battery & power",exact:true}).click();
  await expect(page.locator("#power-result")).toContainText("More evidence");
  await page.getByLabel("Battery / supply model",{exact:true}).fill("QA protected AA supply");
  await page.getByLabel("Supply rating evidence / reference",{exact:true}).fill("Fixture supply specification");
  await page.getByLabel("Supply path",{exact:true}).selectOption("direct");
  for(const [label,value] of [["Lowest loaded source voltage (V)","3.2"],["Highest source voltage (V)","4.8"],["Source continuous current capability (mA)","300"]])await page.getByLabel(label,{exact:true}).fill(value);
  await page.locator('[name="polarityChecked"]').check();
  await page.locator('[name="sourceProtected"]').check();
