// Local-only Workshop Intelligence UI: explicit evidence and no invented AI/hardware features.
import { heading, escape, $, $$ } from "./ui.js";
import { download } from "./storage.js";
import { opportunityList, projectOpportunity, diagnosticProtocol } from "./workshop-intelligence.js";

const asList = (items) => items.length
  ? "<ul>" + items.map((x) => "<li>" + escape(x) + "</li>").join("") + "</ul>"
  : "<p class='muted'>No items in this category.</p>";

export function workshopHTML() {
  return heading("Connect the parts you own to the work you want to do", "Workshop intelligence",
    "Nine inventions · your Rev 4 inventory · safe next tests. Advice is rules-based and does not claim to identify parts or measure hardware.",
    '<a class="button" href="#/components">Open Component Bank →</a>') +
    '<div class="notice">This guide uses catalog evidence and your private, browser-local inventory. An item appearing in a PDF is a potential lead—not a tested, electrically compatible component. Hardware is not connected or controlled from this page.</div>' +
    '<div class="stats intel-stats" id="intel-stats"></div>' +
    '<div class="two-col intel-top">' +
      '<section class="panel"><h2>Build Navigator</h2><label>Choose an invention<select id="intel-project-select"></select></label><div id="intel-project-results"></div></section>' +
      '<section class="panel"><h2>Electronics Detective</h2><label>Search a photographed part, chip or safety note<input id="intel-ref-search" type="search" placeholder="Mouse, R-NZ, battery, 2N4401…"></label><label>Inspect a reference entry<select id="intel-ref-select"></select></label><div id="intel-diagnostic"></div></section>' +
    '</div>' +
    '<section class="intel-priorities"><div class="section-title"><h2>Choose what to work on next</h2><a href="#/salvage">Start a donor record →</a></div><p class="small muted">Ordered by practical, low-cost inspection sequence—not by proven construction readiness. Recorded passing category tests do not certify electrical compatibility.</p><div id="intel-opportunities" class="component-grid"></div></section>';
}

export function projectWorkbookText(result) {
  if (!result) return "";
  const {project,plan,requirements,related} = result;
  return [
    "# McGruber build investigation: " + project.id + " — " + project.name,
    "",
    "Status: proposed bench test, not a verified build.",
    "Mission: " + project.description,
    "",
    "## Safe next action",plan.next,"",
    "## Qualification blocker",plan.gate,"",
    "## Original required component categories",
    ...requirements.map((c) => "- " + c.id + " " + c.component + ": " + c.state + ". " +
      (c.tested.length ? "Recorded passing category test: " + c.tested.map((p) => p.id).join(", ") : "No proven category test.")),
    "",
    "## Rev 4 potential salvage leads (NOT verified compatible)",
    ...related.map((i) => "- " + i.id + " " + i.name + " (PDF page " + i.sourcePage + "): " + i.description),
    "",
    "## Required record before real-world claims",
    "- Record exact part markings, datasheet and package orientation.",
    "- Draw pin-level circuit and verify isolated low-voltage source, protection, current and connectors.",
    "- Record instrument mode, measured values, repeat cycles, failures and power-off state.",
    "- Attach actual evidence in the private Notebook; repeat under expected ambient conditions.",
    "",
    "Generated by McGruber Workshop Intelligence. No physical measurements were performed.",
  ].join("\n");
}

export function diagnosticWorkbookText(info) {
  if (!info) return "";
  return [
    "# McGruber component inspection: " + info.id + " — " + info.title,
    "Original source: McGruber Rev 4 master reference, PDF p." + info.sourcePage,
    "",
    "Safety: " + info.safety,
    "Specific guidance: " + info.technique,
    "",
    "## Safe identification checklist",
    ...info.steps.map((s,i) => "- [ ] " + (i + 1) + ". " + s),
    "",
    "## Fill in ONLY after actually performing tests",
    "Part marking / source:",
    "Tool + mode:",
    "Observed readings:",
    "Expected result:",
    "Actual result / failures:",
    "Uncertainties and next step:",
    "",
    "No automated part identification, signal capture or physical test was performed.",
  ].join("\n");
}

export function mountWorkshop(ctx) {
  const selector = $("#intel-project-select");
  const sourceSelector = $("#intel-ref-select");
  const sourceSearch = $("#intel-ref-search");
  const opportunities = opportunityList(ctx.catalog, ctx.workspace);
  const master = ctx.catalog.rev4Inventory?.items || [];
  const confirmed = ctx.workspace.inventory.filter((p) => p.test?.result === "Pass").length;
  const referenced = new Set(ctx.workspace.inventory.map((p) => p.sourceReferenceId).filter(Boolean));
  const uniqueReferences = master.filter((m) => !m.subassemblyOf);
  $("#intel-stats").innerHTML =
    "<div><strong>" + ctx.workspace.inventory.length + "</strong><span>Personal inventory entries</span></div>" +
    "<div><strong>" + master.length + "</strong><span>Photographed/reference entries</span></div>" +
    "<div><strong>" + uniqueReferences.filter((m) => referenced.has(m.id)).length + "/" + uniqueReferences.length + "</strong><span>Distinct groups imported locally</span></div>" +
    "<div><strong>" + confirmed + "</strong><span>Entries with a recorded passing test (not qualified builds)</span></div>";

  selector.innerHTML = opportunities.map((v) => '<option value="' + escape(v.project.id) + '">' +
    escape(v.project.id + " · " + v.project.name) + "</option>").join("");
  const requested = location.hash.split("/")[2];
  selector.value = opportunities.some((r) => r.project.id === requested) ? requested : "P04";

  function renderProject() {
    const result = projectOpportunity(ctx.catalog, ctx.workspace, selector.value);
    if (!result) return;
    const {project,plan,requirements,related,recorded,missing,needTests} = result;
    $("#intel-project-results").innerHTML =
      '<span class="eyebrow">' + escape(project.id) + " · " + escape(result.displayStatus) + "</span>" +
      "<h3>" + escape(plan.title) + "</h3>" +
      "<p><strong>First useful test:</strong> " + escape(plan.next) + "</p>" +
      '<p class="small muted"><strong>Before calling it a build:</strong> ' + escape(plan.gate) + "</p>" +
      '<div class="row wrap"><span class="pill">' + result.covered + "/" + result.total +
      ' categories with passing tests</span><span class="pill">' + recorded.length + "/" + related.length +
      " suggested Rev 4 leads imported</span></div>" +
      "<details><summary>Original required component categories (" + requirements.length + ")</summary>" +
        (requirements.length ? '<ul>' + requirements.map((x) =>
          '<li><strong>' + escape(x.component) + '</strong> — ' + escape(x.state) +
            (x.candidates.length ? " · Candidates: " + escape(x.candidates.map((p) => p.name).join(", ")) : "") +
          "</li>").join("") + "</ul>" : '<p class="muted">No required rows identified in the original compatibility matrix.</p>') +
      "</details>" +
      "<details open><summary>Likely salvage leads (" + related.length + ")</summary>" +
        '<ul>' + related.map((item) =>
          '<li><button class="intel-text-button" data-intel-ref="' + escape(item.id) + '">' + escape(item.id + " " + item.name) +
          "</button> <span class='small muted'>· " + (referenced.has(item.id) ? "in private inventory" : "only in reference") +
          "; page " + item.sourcePage + "</span></li>").join("") + "</ul>" +
        '<p class="small muted">Candidate groups are for investigation only. No wiring, pinout or rating is inferred.</p>' +
      "</details>" +
      '<p class="small muted">Still without a recorded candidate: ' + missing.length +
      " categories; candidates needing tests: " + needTests.length + ".</p>" +
      '<div class="row wrap intel-actions"><a class="button primary" href="#/project/' + escape(project.id) +
        '/guide">Open build guide</a><a class="button" href="#/notebook/' + escape(project.id) +
        '">Record next test</a><button id="intel-export-project" type="button">Export investigation plan</button></div>';

    $("#intel-export-project").onclick = () =>
      download(projectWorkbookText(result), "mcgruber-" + project.id.toLowerCase() + "-investigation.md", "text/markdown");
    $$("[data-intel-ref]").forEach((el) => el.onclick = () => {
      const ref = master.find((m) => m.id === el.dataset.intelRef);
      if (!ref) return;
      sourceSearch.value = "";
      fillSources(ref.id);
      renderDiagnostic();
      $("#intel-diagnostic").scrollIntoView({block:"nearest"});
    });
    $$("[data-intel-project]").forEach((el) => el.setAttribute("aria-pressed", String(el.dataset.intelProject === selector.value)));
  }

  function fillSources(preferred) {
    const q = sourceSearch.value.toLowerCase().trim();
    const shown = master.filter((item) => !q || JSON.stringify(item).toLowerCase().includes(q));
    const keep = shown.some((m) => m.id === preferred) ? preferred : shown[0]?.id;
    sourceSelector.disabled = !shown.length;
    sourceSelector.innerHTML = shown.length ? shown.map((item) =>
      '<option value="' + escape(item.id) + '">' + escape(item.id + " · " + item.name) + "</option>").join("")
      : '<option value="">No matching reference</option>';
    if (keep) sourceSelector.value = keep;
  }

  function renderDiagnostic() {
    const item = master.find((m) => m.id === sourceSelector.value);
    const info = diagnosticProtocol(item);
    if (!info) {
      $("#intel-diagnostic").innerHTML = '<p class="muted">No matching reference entry. Try different wording.</p>';
      return;
    }
    const personal = ctx.workspace.inventory.find((p) => p.sourceReferenceId === item.id);
    $("#intel-diagnostic").innerHTML =
      '<span class="eyebrow">' + escape(item.id) + ' · PDF PAGE ' + escape(item.sourcePage) + " · " + escape(item.evidence) + "</span>" +
      "<h3>" + escape(item.name) + "</h3>" +
      '<p class="small muted">Model: ' + escape(item.model) + "</p>" +
      '<p class="notice"><strong>Safety:</strong> ' + escape(info.safety) + "</p>" +
      "<p><strong>Recommended test:</strong> " + escape(info.technique) + "</p>" +
      "<details><summary>Inspection checklist</summary>" + asList(info.steps) + "</details>" +
      "<details><summary>Components actually described by the source</summary>" + asList(item.components) + "</details>" +
      '<p class="small muted">' + escape(info.evidence) + "</p>" +
      '<div class="row wrap intel-actions"><a class="button" href="' +
        (personal ? "#/components//" + encodeURIComponent(personal.id) : "#/components") + '">' +
        (personal ? "Open saved part identification" : "Open Component Bank to import") + '</a>' +
        '<button id="intel-export-diagnostic" type="button">Export test worksheet</button></div>';
    $("#intel-export-diagnostic").onclick = () =>
      download(diagnosticWorkbookText(info), "mcgruber-" + item.id.toLowerCase() + "-checklist.md", "text/markdown");
  }
  $("#intel-opportunities").innerHTML = opportunities.map((m) =>
    '<article class="panel component intel-opportunity"><span class="eyebrow">' + escape(m.project.id) +
      " · Practical priority " + m.plan.priority + "</span><h3>" + escape(m.project.name) + "</h3>" +
      '<p class="small">' + escape(m.plan.next) + "</p>" +
      '<p class="small muted">Potential Rev 4 leads: ' + m.related.length + " · Tested required categories: " +
        m.covered + "/" + m.total + "</p>" +
      '<button type="button" data-intel-project="' + escape(m.project.id) + '">Investigate this project</button></article>'
    ).join("");
  $$("[data-intel-project]").forEach((button) => button.onclick = () => {
    selector.value = button.dataset.intelProject;
    renderProject();
    selector.scrollIntoView({block:"nearest"});
  });

  selector.onchange = renderProject;
  sourceSelector.onchange = renderDiagnostic;
  sourceSearch.oninput = () => { fillSources(sourceSelector.value); renderDiagnostic(); };
  fillSources("REF-16");
  renderProject();
  renderDiagnostic();
}
